  static AcademicKnowledgeUnit? byId(String id) {
    for (final unit in units) {
      if (unit.id == id) return unit;
    }
    return null;
  }

  static List<AcademicKnowledgeUnit> forArea(String areaId) =>
      units.where((unit) => unit.areaId == areaId).toList(growable: false);

  static List<AcademicKnowledgeUnit> forCourse(AcademicCourse course) =>
      course.knowledgeUnitIds.map(byId).whereType<AcademicKnowledgeUnit>().toList(growable: false);
